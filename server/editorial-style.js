const rejectedPatterns = [
  /그대로\s*남(?:는|는다|아|았|을|게|고|지|습니다|았다)/,
  /앞(?:선다|선다는|서는|섰다|섰다는|서야|서고|서며|섭니다|설\s*것)/,
  /판단(?:은|이|만큼은)?\s*(?:매우\s*|아주\s*|더\s*)?(?:분명|명확|확실)/,
  /(?:분명|명확|확실)(?:한|해진)\s*판단/,
];

export function rejectedEditorialPhrase(value) {
  const text=String(value||'').normalize('NFC');
  for(const pattern of rejectedPatterns){const match=text.match(pattern);if(match)return match[0];}
  return null;
}
