"""Generate shared/logo.js: the "D.one" wordmark as a Playfair Display Bold path.

PNG export renders SVG through sharp (librsvg + pango), which on macOS only sees
system-installed fonts, so project-local Playfair text falls back to sans-serif.
Drawing the wordmark as outlines keeps preview and export identical.

Usage (one-off, needs `pip install fonttools uharfbuzz`):
    python scripts/build-logo-path.py
"""

from __future__ import annotations

import io
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
FONT_PATH = ROOT / "public" / "fonts" / "PlayfairDisplay.ttf"
OUTPUT_PATH = ROOT / "shared" / "logo.js"
TEXT = "D.one"
WEIGHT = 700


def bold_instance() -> bytes:
    """Return the Playfair Display variable font pinned to the logo weight."""
    font = instantiateVariableFont(TTFont(FONT_PATH), {"wght": WEIGHT})
    buffer = io.BytesIO()
    font.save(buffer)
    return buffer.getvalue()


def shaped_path(font_bytes: bytes) -> tuple[str, float]:
    """Shape TEXT with kerning and return (em-normalized y-down path, advance)."""
    font = TTFont(io.BytesIO(font_bytes))
    upem = font["head"].unitsPerEm
    glyph_set = font.getGlyphSet()
    glyph_order = font.getGlyphOrder()

    hb_font = hb.Font(hb.Face(font_bytes))
    buffer = hb.Buffer()
    buffer.add_str(TEXT)
    buffer.guess_segment_properties()
    hb.shape(hb_font, buffer, {"kern": True, "liga": True})

    pen = SVGPathPen(glyph_set, ntos=lambda value: f"{value:.4f}".rstrip("0").rstrip("."))
    cursor = 0
    for info, position in zip(buffer.glyph_infos, buffer.glyph_positions):
        x = (cursor + position.x_offset) / upem
        y = position.y_offset / upem
        # Font units are y-up; SVG is y-down with the origin on the baseline.
        transform = (1 / upem, 0, 0, -1 / upem, x, -y)
        glyph_set[glyph_order[info.codepoint]].draw(TransformPen(pen, transform))
        cursor += position.x_advance
    return pen.getCommands(), cursor / upem


def main() -> None:
    path, advance = shaped_path(bold_instance())
    OUTPUT_PATH.write_text(
        "// Generated by scripts/build-logo-path.py — do not edit by hand.\n"
        f"// Playfair Display wght {WEIGHT}, 1em = 1 unit, origin on the baseline.\n"
        f"export const LOGO_TEXT='{TEXT}';\n"
        f"export const LOGO_ADVANCE={advance:.4f};\n"
        f"export const LOGO_PATH='{path}';\n"
    )
    print(f"Wrote {OUTPUT_PATH.relative_to(ROOT)} ({len(path)} chars, advance {advance:.4f}em)")


if __name__ == "__main__":
    main()
